'use strict';
/**
 * data/*.json  ->  a single idempotent SQL seed.
 *
 *   node scripts/db-import.js > supabase/seed.sql
 *
 * Emits SQL rather than calling an API, for three reasons: it needs no credentials, so
 * nobody has to hand a service-role key to a script or paste one into a chat; it can be
 * applied through the Supabase SQL Editor exactly like the schema; and it is reviewable
 * as a diff before it touches anything.
 *
 * Ids are UUIDv5 derived from natural keys, so re-running produces identical rows and
 * `on conflict do nothing` makes the whole file safe to apply repeatedly.
 */
const fs = require('fs');
const path = require('path');
const { id, q, qn, qb, qa, insert, parsePeriod } = require('./lib/csw-db');

const D = (f) => JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'data', f), 'utf8'));
const data = {
  brands: D('brands.json'), operators: D('operators.json'), news: D('news.json'),
  transactions: D('transactions.json'), realestate: D('realestate.json'),
  expansion: D('expansion.json'), movement: D('movement.json'), markets: D('markets.json'),
  research: D('research.json'), datacenter: D('datacenter.json'),
  consumer: D('consumer.json'), events: D('events.json')
};
const sources = D('sources.json');

const out = [];
const say = (s) => out.push(s);
const section = (t) => say(`\n-- ${'='.repeat(74)}\n-- ${t}\n-- ${'='.repeat(74)}\n`);

const SRC = (k) => (k && sources[k] ? id('source', k) : null);
const srcq = (k) => (SRC(k) ? q(SRC(k)) : 'null');
const warn = [];

/* Everything the site labels "chicken brand". Non-chicken brands come from operators. */
const brandId = (slug) => id('brand', slug);
const coId    = (slug) => id('company', slug);
const slugify = (s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

say(`-- Generated by scripts/db-import.js. Do not edit.
-- Source of truth is data/*.json until Phase 4 flips the direction.
-- Safe to re-run: every insert is on-conflict-do-nothing over deterministic ids.

begin;`);

/* ---------------------------------------------------------------- sources */
section('sources');
say(insert('public.sources',
  ['id','key','publisher','title','url','date_label','published_on','source_type'],
  Object.entries(sources).map(([k, s]) => {
    const p = parsePeriod(s.date);
    const type = /sec\.gov|EDGAR/i.test(s.url + s.pub) ? 'sec_filing'
      : /Boulder Group|TopNetLease|Bull Realty|CoStar/i.test(s.pub) ? 'brokerage_report'
      : /USDA|Census/i.test(s.pub) ? 'government'
      : /FDD/i.test(s.title) ? 'fdd' : 'trade_press';
    return [q(id('source', k)), q(k), q(s.pub), q(s.title), q(s.url), q(s.date),
            p.start ? q(p.start) : 'null', q(type)];
  }), '(key)'));

