section('category subject — the anchor for industry-level figures');
say(`insert into public.markets (id, slug, name, is_published) values
  (${q(id('category','us-chicken'))}, 'us-chicken-category', 'U.S. chicken restaurant category', false)
on conflict (slug) do nothing;`);

