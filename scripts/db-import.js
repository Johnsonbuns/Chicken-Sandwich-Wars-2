/* ------------------------------------------------------------ entity notes */
section('entity notes — the sourced-bullet pattern, six arrays unified');
const noteRows = [], noteSrcRows = [];
const pushNote = (key, kind, subjKind, subjId, body, srcs, o = {}) => {
  const nid = id('note', key);
  noteRows.push([q(nid), q(subjKind), q(subjId), q(kind), q(o.label), q(body),
    q(o.period), srcq(srcs[0]), String(o.ordinal || 0)]);
  srcs.filter(Boolean).forEach((s, i) => noteSrcRows.push([q(nid), srcq(s), String(i)]));
};
data.brands.forEach((b) => {
  (b.pipeline || []).forEach((p, i) =>
    pushNote(`pipeline:${b.slug}:${i}`, 'pipeline', 'brand', brandId(b.slug), p.text, [p.src], { ordinal: i }));
  if (b.realEstate && b.realEstate.notes)
    pushNote(`re-note:${b.slug}`, 'real_estate_note', 'brand', brandId(b.slug),
      b.realEstate.notes, b.realEstate.notesSrc || []);
});
data.operators.forEach((o) => (o.facts || []).forEach((f, i) =>
  pushNote(`opfact:${o.slug}:${i}`, 'operator_fact', 'company', coId(o.slug), f.text, [f.src],
    { period: f.asOf, ordinal: i })));
data.markets.forEach((m) => {
  (m.activity || []).forEach((a, i) =>
    pushNote(`mkt-act:${m.slug}:${i}`, 'market_activity', 'market', id('market', m.slug), a.text, [a.src], { ordinal: i }));
  (m.watch || []).forEach((w, i) =>
    pushNote(`mkt-watch:${m.slug}:${i}`, 'market_watch', 'market', id('market', m.slug), w, [], { ordinal: i }));
});
const cat = id('category', 'us-chicken');
data.realestate.leaseIntel.forEach((x, i) =>
  pushNote(`lease:${i}`, 'lease_intel', 'category', cat, x.text, [x.src], { label: x.label, ordinal: i }));
data.realestate.supply.forEach((x, i) =>
  pushNote(`supply:${i}`, 'supply', 'category', cat, x.text, [x.src], { label: x.label, ordinal: i }));
data.realestate.marketConditions.forEach((x, i) =>
  pushNote(`mktcond:${i}`, 'real_estate_note', 'category', cat, x.text, [x.src], { ordinal: i }));
data.consumer.context.forEach((x, i) =>
  pushNote(`ctx:${i}`, 'consumer_context', 'category', cat, x.text, [x.src], { ordinal: i }));
say(insert('public.entity_notes',
  ['id','subject_type','subject_id','kind','label','body_md','period_label','source_id','ordinal'], noteRows));
say('\n' + insert('public.note_sources', ['note_id','source_id','ordinal'], noteSrcRows, '(note_id, source_id)'));

/* --------------------------------------------------- properties & movement */
section('properties, occupancies and the system movement feed');
const AGG = /^(United States|National|Global|Eight U\.S\. markets|.*markets in one day)/i;
const propRows = [], occRows = [], moveRows = [];
const movement = [...data.movement.openings.map((m, i) => ({ ...m, dir: 'opening', i })),
                  ...data.movement.closures.map((m, i) => ({ ...m, dir: 'closure', i }))];
for (const ev of movement) {
  const key = `${ev.dir}:${ev.i}`;
  const isAggregate = ev.count != null || AGG.test(ev.location || '');
  let pid = null;
  if (!isAggregate) {
    pid = id('property', `${ev.brand}:${ev.location}`);
    const parts = String(ev.location).split(',').map((s) => s.trim());
    const st = parts.length > 1 ? parts[parts.length - 1] : null;
    propRows.push([q(pid), 'null', q(parts.length > 1 ? parts[parts.length - 2] : parts[0]),
      q(st && st.length <= 2 ? st : null), q(ev.location), `'operating'`, `'editorial'`,
      `'verified'`, 'true', srcq(ev.src)]);
    occRows.push([q(id('occ', key)), q(pid), q(brandId(ev.brand)),
      ev.dir === 'opening' ? `'open'` : `'closed'`,
      ev.dir === 'opening' ? q(parsePeriod(ev.date).start) : 'null',
      ev.dir === 'closure' ? q(parsePeriod(ev.date).start) : 'null',
      q(ev.detail), q(ev.date), srcq(ev.src)]);
  }
  const p = parsePeriod(ev.date);
  moveRows.push([q(id('move', key)), q(brandId(ev.brand)), q(ev.dir), q(ev.date),
    p.start && p.start === p.end ? q(p.start) : 'null', p.start ? q(p.start) : 'null',
    p.end ? q(p.end) : 'null', qn(ev.count), q(ev.location), q(ev.detail),
    pid ? q(pid) : 'null', srcq(ev.src), String(ev.i)]);
}
say(insert('public.properties',
  ['id','address_line1','city','state','location_label','status','record_source',
   'verification','is_published','source_id'], propRows));
say('\n' + insert('public.property_occupancies',
  ['id','property_id','brand_id','status','opened_on','closed_on','detail_md','date_label','source_id'], occRows));
say('\n' + insert('public.system_movements',
  ['id','brand_id','direction','date_label','occurred_on','period_start','period_end',
   'unit_count','location_label','detail_md','property_id','source_id','ordinal'], moveRows));

/* ----------------------------------------------------------- transactions */
section('transactions, the properties they convey, and listings');
const TXK = { 'Property sale':'property_sale','Portfolio acquisition':'portfolio_acquisition',
  'Listing':'listing','Brand acquisition':'brand_acquisition','Franchisee portfolio':'franchisee_portfolio',
  'Bankruptcy sale':'bankruptcy_sale','Chapter 11 / company-store sale':'company_store_sale',
  'Growth investment':'growth_investment' };
const txRows = [], txPropRows = [], listRows = [], listPropRows = [];
data.transactions.property.forEach((t, i) => {
  const bslug = (data.brands.find((b) => t.brand.toLowerCase().includes(b.name.split(' ')[0].toLowerCase())) || {}).slug;
  if (t.type === 'Listing') {
    const lid = id('listing', `tx:${i}`);
    listRows.push([q(lid), q(`${t.brand} — ${t.location}`), q(t.detail), `'active'`,
      qn(t.price), qn(t.capRate), 'true', srcq(t.src), q(t.date), q(t.location), q(t.term),
      bslug ? q(brandId(bslug)) : 'null']);
    return;
  }
  const tid = id('tx', `property:${i}`);
  const specific = t.location && !/not disclosed/i.test(t.location) && /,/.test(t.location);
  txRows.push([q(tid), q(TXK[t.type] || 'property_sale'), `'property'`, q(t.date),
    q(parsePeriod(t.date).start), qn(t.price), qb(t.price != null), qn(t.capRate), 'null',
    'null', bslug ? q(brandId(bslug)) : 'null', q(t.location), q(t.term), q(t.detail),
    srcq(t.src), 'true', 'null', 'null']);
  if (specific) {
    const pid = id('property', `tx:${t.brand}:${t.location}`);
    propRows.push([q(pid), 'null', q(String(t.location).split(',').slice(-2, -1)[0] || t.location),
      'null', q(t.location), `'sold'`, `'editorial'`, `'verified'`, 'true', srcq(t.src)]);
    txPropRows.push([q(tid), q(pid)]);
  }
});
data.transactions.corporate.forEach((t, i) => {
  const tid = id('tx', `corporate:${i}`);
  const target = data.operators.find((o) => o.name === t.target)
    || data.brands.find((b) => b.name === t.target);
  const isBrand = target && data.brands.includes(target);
  txRows.push([q(tid), q(TXK[t.type] || 'brand_acquisition'), `'company'`, q(t.date),
    q(parsePeriod(t.date).start), qn(t.value), qb(t.value != null), 'null', 'null',
    (target && !isBrand) ? q(coId(target.slug)) : 'null', isBrand ? q(brandId(target.slug)) : 'null',
    'null', 'null', q(t.detail), srcq(t.src), 'true', q(t.target), q(t.acquirer)]);
});
/* Emit the extra properties discovered above alongside the originals. */
say(insert('public.properties',
  ['id','address_line1','city','state','location_label','status','record_source',
   'verification','is_published','source_id'], propRows.slice(occRows.length)));
say('\n' + insert('public.transactions',
  ['id','kind','subject','date_label','closed_on','price_usd','is_price_disclosed','cap_rate_pct',
   'noi_usd','buyer_company_id','brand_id','location_label','term_label','detail_md','source_id',
   'is_published','target_label','acquirer_label'], txRows));
say('\n' + insert('public.transaction_properties', ['transaction_id','property_id'], txPropRows,
  '(transaction_id, property_id)'));
say('\n' + insert('public.listings',
  ['id','headline','summary_md','status','asking_price_usd','cap_rate_pct','authorization_on_file',
   'source_id','date_label','location_label','term_label','brand_id'], listRows));

