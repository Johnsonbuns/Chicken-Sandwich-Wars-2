data.news.forEach((n, i) => {
  const aid = id('article', `news:${i}`);
  artRows.push([q(aid), q(`news-${i}-${slugify(n.title).slice(0, 60)}`), `'news'`, q(n.cat),
    q(n.title), 'null', 'null', q(n.means), 'null', q(n.date),
    q(parsePeriod(n.date).start), `'published'`, srcq(n.src), String(i)]);
  if (n.brand) artEnt.push([q(aid), `'brand'`, q(brandId(n.brand)), `'about'`]);
  artSrc.push([q(aid), srcq(n.src), '0']);
});
data.research.forEach((r, i) => {
  const aid = id('article', `research:${r.slug}`);
  artRows.push([q(aid), q(r.slug), `'research'`, 'null', q(r.title), q(r.dek),
    q(JSON.stringify(r.sections)), 'null', qn(parseInt(r.readTime, 10)), q(r.date),
    'null', `'published'`, 'null', String(i)]);
  const seen = new Set();
  r.sections.forEach((s) => (s.srcs || []).forEach((k) => {
    if (seen.has(k)) return; seen.add(k);
    artSrc.push([q(aid), srcq(k), String(seen.size - 1)]);
  }));
});
say(insert('public.articles',
  ['id','slug','kind','category','title','dek','body','means_md','read_minutes','date_label',
   'published_at','status','primary_source_id','sort_index'], artRows, '(slug)'));
say('\n' + insert('public.article_entities', ['article_id','subject_type','subject_id','relation'],
  artEnt, '(article_id, subject_type, subject_id)'));
say('\n' + insert('public.article_sources', ['article_id','source_id','ordinal'], artSrc,
  '(article_id, source_id)'));

