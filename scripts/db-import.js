section('facts — every published figure, individually sourced');
const snake = (k) => k.replace(/([a-z])([A-Z])/g,'$1_$2').replace(/([A-Z]+)([A-Z][a-z])/g,'$1_$2')
                      .replace(/([a-zA-Z])(\d)/g,'$1_$2').toLowerCase();
const factRows = [];
const pushFact = (kind, subj, metric, value, unit, period, src, opts = {}) => {
  if (src == null) { warn.push(`fact ${metric} on ${kind} has no source — skipped`); return; }
  const p = parsePeriod(period);
  factRows.push([q(id('fact', `${kind}:${subj}:${metric}:${period}`)), q(kind), q(subj), q(metric),
    qn(value), 'null', q(unit), q(period), p.start ? q(p.start) : 'null', p.end ? q(p.end) : 'null',
    'null', q(src), q(opts.derivation || 'reported'), q(opts.note)]);
};

for (const b of data.brands) {
  for (const [k, st] of Object.entries(b.stats || {})) {
    const unit = st.fmt === 'usd' ? 'usd' : st.fmt === 'pct' ? 'pct' : 'count';
    pushFact('brand', brandId(b.slug), snake(k), st.v, unit, st.asOf, SRC(st.src), { note: st.note });
  }
  /* Derived numerics that feed the score. They carry no src of their own, so each
     inherits the source of the published figure it is computed from. */
  const m = b.metrics || {};
  const stat = (...names) => names.map((n) => b.stats && b.stats[n]).find(Boolean);
  const fallback = Object.values(b.stats || {})[0];
  const pick = (s) => SRC((s || fallback || {}).src);
  const period = (s) => ((s || fallback || {}).asOf) || 'latest';
  const map = [
    ['auv_usd', m.auvUsd, 'usd', stat('auv','blendedAuv'), m.auvNote, false],
    ['unit_growth_pct', m.unitGrowthPct, 'pct', stat('usUnits','globalUnits','usCanadaUnits','currentUnits'), null, m.unitGrowthDerived],
    ['sales_growth_pct', m.salesGrowthPct, 'pct', stat('systemwideSales','globalSales'), m.salesGrowthNote, m.salesGrowthDerived],
    ['comps_pct', m.compsPct, 'pct', stat('compsLatest','compsFY'), null, false],
    ['cap_rate_mid', m.capRateMid, 'pct', null, m.capRateBasis, false]
  ];
  for (const [key, val, unit, s, note, derived] of map) {
    if (val == null) continue;
    const src = key === 'cap_rate_mid'
      ? SRC((b.realEstate && b.realEstate.capSrc && b.realEstate.capSrc[0]) || (fallback || {}).src)
      : pick(s);
    pushFact('brand', brandId(b.slug), key, val, unit, period(s), src,
      { derivation: derived ? 'derived' : 'reported', note });
  }
  if (m.netClosures != null)
    pushFact('brand', brandId(b.slug), 'net_unit_decline', m.netClosures ? 1 : 0, 'ratio',
      period(fallback), pick(fallback), { derivation: 'derived' });
}

for (const o of data.operators) {
  const src = SRC(((o.facts || [])[0] || {}).src);
  if (o.chickenUnits != null)
    pushFact('company', coId(o.slug), 'operator_chicken_units', o.chickenUnits, 'count',
      ((o.facts || [])[0] || {}).asOf || 'latest', src, { note: o.chickenUnitsNote });
  if (o.totalUnits != null)
    pushFact('company', coId(o.slug), 'operator_total_units', o.totalUnits, 'count',
      ((o.facts || [])[0] || {}).asOf || 'latest', src);
}

const BENCH = { 'Corporate-guaranteed QSR':'cap_rate_corporate_qsr',
  'Franchisee-guaranteed QSR':'cap_rate_franchisee_qsr',
  'All single-tenant net lease':'cap_rate_all_net_lease',
  'Single-tenant retail':'cap_rate_single_tenant_retail',
  "Premium QSR ground lease (McDonald's / Chick-fil-A)":'cap_rate_premium_ground_lease' };
for (const bm of data.realestate.benchmarks) {
  const key = BENCH[bm.label];
  if (!key) { warn.push(`benchmark "${bm.label}" has no metric key`); continue; }
  const cat = id('category', 'us-chicken');
  const p = parsePeriod(bm.asOf);
  factRows.push([q(id('fact', `category:${cat}:${key}:${bm.asOf}`)), `'category'`, q(cat), q(key),
    qn(parseFloat(bm.value)), 'null', `'pct'`, q(bm.asOf), p.start ? q(p.start) : 'null',
    p.end ? q(p.end) : 'null', 'null', srcq(bm.src), `'reported'`, q(bm.change)]);
}
say(insert('public.facts',
  ['id','subject_type','subject_id','metric_key','value_numeric','value_text','unit',
   'period_label','period_start','period_end','as_of','source_id','derivation','note'], factRows));

